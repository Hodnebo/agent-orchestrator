func TestBranchScrubberUsesCommentMarkersByExtension(t *testing.T) {
	cases := []struct {
		path, line string
		want       bool
	}{
		{"src/check.ts", "if this.#a > 0 {", true},
		{"src/check.ts", "if --n > 0 {", true},
		{"scripts/check.sh", "cmd --flag || exit", true},
		{"scripts/marker.py", "value# if hidden && count > 0", false},
		{"scripts/marker.sh", "echo# if this is still code && count > 0", true},
		{"src/form.clj", "; if this is a comment && not source", false},
		{"src/form.clj", "(if (= count 1) value nil)", true},
		{"templates/page.html", "<!-- if this is a comment && not source -->", false},
		{"templates/page.html", "if ready && count > 0 {", true},
	}
	for _, tt := range cases {
		got := scrubbedBranchConditions(tt.path, tt.line)
		if (len(got) > 0) != tt.want {
			t.Errorf("%s %q: branch detected = %t, want %t (scrubbed %q)", tt.path, tt.line, len(got) > 0, tt.want, got)
		}
	}
}

